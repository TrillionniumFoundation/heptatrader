def patch_cpp_binding() -> None:
    path = ROOT / "HeptaTrade/tool_host/typed_tool_protocol.cpp"
    text = path.read_text(encoding="utf-8")
    text = replace_once(
        text,
        '#include "../tools/trading_tool_wire_contract.h"\n',
        '#include "../tools/trading_tool_wire_contract.h"\n'
        '#include "../numeric/fixed_decimal.h"\n',
        "numeric include",
    )
    pattern = re.compile(
        r"enum FieldId\n\{.*?\n\};\n\n"
        r"const char\* FieldName\(unsigned int id\)\n\{.*?\n\}\n",
        re.DOTALL,
    )
    marker = (
        "// HEPTA-GENERATED-WIRE-CATALOG-BEGIN\n"
        "// generated by scripts/generate_contract_bindings.py\n"
        "// HEPTA-GENERATED-WIRE-CATALOG-END\n"
    )
    text, count = pattern.subn(marker, text)
    if count != 1:
        raise SystemExit(f"C++ generated region: expected one match, found {count}")

    number_marker = "template <typename T>\nstd::string Number(T value)\n"
    number_overload = '''std::string Number(double value)
{
    HeptaFixedDecimal fixed;
    std::string reason;
    if (!HeptaFixedDecimal::FromDoubleExact(value, fixed, reason))
        return "invalid";
    return fixed.ToCanonicalString();
}

'''
    text = replace_once(
        text,
        number_marker,
        number_overload + number_marker,
        "fixed encoder overload",
    )

    parse_pattern = re.compile(
        r"bool ParseDouble\(const std::string& value, double& out\)\n"
        r"\{.*?\n\}\n\n"
        r"typedef std::map<unsigned int, std::string> DecodedFields;",
        re.DOTALL,
    )
    parse_replacement = '''bool ParseDouble(const std::string& value, double& out)
{
    if (!CanonicalFloating(value)) return false;
    HeptaFixedDecimal fixed;
    std::string reason;
    if (!HeptaFixedDecimal::ParseCanonical(value, fixed, reason))
        return false;
    out = fixed.ToDouble();
    return true;
}

typedef std::map<unsigned int, std::string> DecodedFields;'''
    text, count = parse_pattern.subn(parse_replacement, text)
    if count != 1:
        raise SystemExit(f"fixed decoder: expected one match, found {count}")
    path.write_text(text, encoding="utf-8")


def patch_python_binding() -> None:
    path = ROOT / "adapters/mcp/hepta_mcp_server.py"
    text = path.read_text(encoding="utf-8")
    text = replace_once(
        text,
        'PROTOCOL_NAME = "hepta.agent-tools"\nPROTOCOL_VERSION = 1\n',
        "# HEPTA-GENERATED-WIRE-CATALOG-BEGIN\n"
        "# generated by scripts/generate_contract_bindings.py\n"
        "# HEPTA-GENERATED-WIRE-CATALOG-END\n",
        "Python generated region",
    )
    field_pattern = re.compile(r"FIELD_IDS = \{\n.*?\n\}\n\n", re.DOTALL)
    text, count = field_pattern.subn("", text, count=1)
    if count != 1:
        raise SystemExit(f"Python FIELD_IDS: expected one match, found {count}")

    alias_pattern = re.compile(
        r"# The public Agent contract uses domain names.*?"
        r"TARGET_INTENT_TOOLS = frozenset\(\{\n.*?\n\}\)\n\n",
        re.DOTALL,
    )
    text, count = alias_pattern.subn("", text, count=1)
    if count != 1:
        raise SystemExit(f"Python aliases: expected one match, found {count}")

    marker = "\ndef scalar_text(value):\n"
    helper = '''
def _fixed_decimal_text(value):
    if not math.isfinite(value):
        raise ValueError("tool arguments must contain finite numbers")
    if value == 0.0 and math.copysign(1.0, value) < 0.0:
        raise ValueError("tool arguments must use canonical zero")
    scaled = value * NUMERIC_SCALE
    nearest = round(scaled)
    if abs(scaled - nearest) > 0.000001:
        raise ValueError(
            "tool numeric argument does not match fixed numeric policy"
        )
    if abs(nearest) > NUMERIC_MAXIMUM_RAW:
        raise ValueError("tool numeric argument exceeds fixed numeric range")
    negative = nearest < 0
    magnitude = abs(nearest)
    whole, fraction = divmod(magnitude, NUMERIC_SCALE)
    text = str(whole)
    if fraction:
        text += "." + str(fraction).rjust(6, "0").rstrip("0")
    return "-" + text if negative else text

'''
    text = replace_once(
        text,
        marker,
        "\n" + helper + "def scalar_text(value):\n",
        "Python fixed helper",
    )
    text = replace_once(
        text,
        "    if isinstance(value, float):\n"
        "        if not math.isfinite(value):\n"
        "            raise ValueError(\"tool arguments must contain finite numbers\")\n"
        "        if value == 0.0 and math.copysign(1.0, value) < 0.0:\n"
        "            raise ValueError(\"tool arguments must use canonical zero\")\n"
        "        return str(value)\n",
        "    if isinstance(value, float):\n"
        "        return _fixed_decimal_text(value)\n",
        "Python scalar fixed conversion",
    )
    path.write_text(text, encoding="utf-8")


