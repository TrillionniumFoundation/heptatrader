def patch_schema_checker() -> None:
    path = ROOT / "scripts/check_schema_catalog.py"
    text = path.read_text(encoding="utf-8")
    marker = (
        "    if catalog.get(\"protocol_version\") != 1:\n"
        "        errors.append(\"tool catalog protocol version mismatch\")\n"
    )
    addition = marker + '''    numeric_policy = catalog.get("numeric_policy")
    if numeric_policy != {
        "id": "hepta.numeric.fixed-v1",
        "scale": 1_000_000,
        "maximum_raw": 9_000_000_000_000_000,
    }:
        errors.append("tool catalog numeric policy mismatch")
    fields = catalog.get("fields")
    if not isinstance(fields, list) or len(fields) != 26:
        errors.append("tool catalog field map is incomplete")
    else:
        actual_fields = {
            item.get("name"): item.get("id")
            for item in fields if isinstance(item, dict)
        }
        if actual_fields != CANONICAL_FIELD_IDS:
            errors.append("tool catalog field map drift")
        actual_symbols = {
            item.get("symbol"): (item.get("id"), item.get("name"))
            for item in fields if isinstance(item, dict)
        }
        if actual_symbols != CPP_FIELD_SYMBOLS:
            errors.append("tool catalog C++ field symbol drift")
    if catalog.get("target_intent_aliases") != TARGET_INTENT_TO_WIRE:
        errors.append("tool catalog target alias drift")
    if frozenset(catalog.get("target_intent_tools", [])) != TARGET_INTENT_TOOLS:
        errors.append("tool catalog target tool scope drift")
'''
    text = replace_once(text, marker, addition, "schema catalog generated fields")
    path.write_text(text, encoding="utf-8")


def patch_governance() -> None:
    path = ROOT / "docs/modules/source-ownership-registry-v1.json"
    value = json.loads(path.read_text(encoding="utf-8"))
    value["physical_ownership_rules"].append({
        "id": "numeric-core",
        "selector": {"kind": "directory", "path": "HeptaTrade/numeric/"},
        "physical_owner": "hepta.numeric.core",
        "priority": 200,
    })
    path.write_text(
        json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )

    path = ROOT / "docs/modules/manifests/hepta-numeric-core.json"
    value = json.loads(path.read_text(encoding="utf-8"))
    value["lifecycle"] = "current"
    value["verification"] = ["numeric-negative", "numeric-properties"]
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    path = ROOT / "docs/modules/manifests/hepta-protocol-contracts.json"
    value = json.loads(path.read_text(encoding="utf-8"))
    dependencies = value.setdefault("allowed_dependencies", [])
    if "hepta.numeric.core" not in dependencies:
        dependencies.append("hepta.numeric.core")
        dependencies.sort()
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    path = ROOT / "docs/verification/test-matrix-v2.json"
    value = json.loads(path.read_text(encoding="utf-8"))
    for check in value["checks"]:
        if check["id"] == "numeric-properties":
            check["state"] = "implemented"
            check["evidence"] = (
                "fixed decimal core, overflow and cross-binding quantization tests"
            )
        elif check["id"] == "tool-catalog-drift":
            check["evidence"] = (
                "generated C++/Python/MCP binding parity and schema catalog checker"
            )
    path.write_text(
        json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )

    path = ROOT / "docs/architecture/NUMERIC-POLICY.md"
    text = path.read_text(encoding="utf-8")
    old = (
        "## Migration\n\n"
        "当前 mixed-double 接缝标记为 G-NUM-001。迁移按 boundary type → adapter conversion → portfolio/risk → intent/permit → journal/event 顺序进行，并用 golden replay 证明经济和执行语义差异。\n"
    )
    new = (
        "## Implemented boundary\n\n"
        "`hepta.numeric.fixed-v1` 使用有符号 64 位 microunits（scale `1,000,000`），"
        "并把 raw 范围限制在 `±9,000,000,000,000,000`，使兼容 double 在规范化后仍保留"
        "单 microunit 整数身份。typed C++ wire 与 Python/MCP bridge 均从"
        "`schemas/tool-catalog-v1.json` 取得同一 numeric policy；编码输出 canonical decimal，"
        "解码拒绝 NaN、Inf、负零、范围溢出和超过六位小数的 scale mismatch。"
        "旧执行结构中的 double 仅是固定点验证后的兼容投影，不再是跨信任边界的权威表示。\n"
    )
    path.write_text(replace_once(text, old, new, "numeric status"), encoding="utf-8")


def main() -> None:
    extend_catalog()
    patch_cpp_binding()
    patch_python_binding()
    patch_cmake()
    patch_dev_loop()
    patch_schema_checker()
    patch_governance()
    subprocess.run(
        ["python3", "scripts/generate_contract_bindings.py", "--write"],
        cwd=ROOT,
        check=True,
    )
    subprocess.run(
        ["python3", "scripts/generate_documentation_views.py", "--write"],
        cwd=ROOT,
        check=True,
    )
    WORKFLOW.unlink()
    SELF.unlink()


if __name__ == "__main__":
    main()
